/**
 * E'lon ekranlarining tarjima lug'ati.
 *
 * Ekran matnlari kodda o'zbekcha yozilgan va shundayligicha qoladi — ular joyida
 * o'qilishi qulay. Tarjima chizish paytida [lt] orqali olinadi; lug'atda topilmagan
 * matn o'zbekcha holicha ko'rinadi, ya'ni yangi satr qo'shilganda ekran buzilmaydi.
 *
 * Domen katalogining lug'ati alohida (`ListingL10n`): u kalitlar bilan yonma-yon turadi
 * va serverdagi spetsifikatsiyaga bog'langan.
 */
internal fun lt(uz: String): String = when (AppLocale.current) {
    AppLanguage.UZ -> uz
    AppLanguage.EN -> EN[uz] ?: uz
    AppLanguage.RU -> RU[uz] ?: uz
}

/** Pul birligi — summadan keyin qo'yiladi. */
internal fun currency(): String = AppLocale.pick(en = "UZS", ru = "сум", uz = "so'm")

/**
 * Ichida son bo'lgan yorliqlar — lug'atga tushmaydi (kalit har safar boshqacha bo'lardi),
 * shuning uchun uchta variant shu yerda yonma-yon turadi.
 */
