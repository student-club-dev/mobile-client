        AppLocale.pick("$shown of $total", "$shown из $total", "$total tadan $shown tasi")
    fun moreBranches(n: Int) = AppLocale.pick(" +$n branches", " +$n филиалов", " +$n filial")
    fun maxImages(n: Int) = AppLocale.pick("At most $n photos", "Максимум $n фото", "Maksimal $n ta rasm")
    fun emptyFields(n: Int) = AppLocale.pick(
        "$n fields are still empty — marked in red above.",
        "Не заполнено $n полей — отмечены красным выше.",
        "To'ldirilmagan $n ta joy bor — yuqorida qizil bilan belgilandi.",
    )
    fun serviceOf(type: String) = AppLocale.pick("$type service", "Услуга: $type", "$type xizmati")
    fun studentPays(amount: String) = AppLocale.pick(
        "The student pays: $amount ${currency()}",
        "Студент платит: $amount ${currency()}",
        "Talaba to'laydi: $amount ${currency()}",
    )
    fun totalTenants(n: Int) = AppLocale.pick(
        "$n people will live in the home", "В жилье будет $n человек", "Uyda jami $n kishi bo'ladi",
    )
    fun priceFrom(label: String) = AppLocale.pick("$label — from", "$label — от", "$label — dan")
    fun priceTo(label: String) = AppLocale.pick(
        "$label — to (optional)", "$label — до (необязательно)", "$label — gacha (ixtiyoriy)",
    )
    fun daysFromToday(n: Int) = AppLocale.pick("$n days from today", "$n дней с сегодня", "Bugundan boshlab $n kun")
    fun days(n: Int) = AppLocale.pick("$n days", "$n дн.", "$n kun")
    fun inDays(n: Int) = AppLocale.pick("in $n days", "через $n дн.", "$n kundan keyin")
    fun people(n: Int) = AppLocale.pick("$n people", "$n чел.", "$n kishi")
    fun months(n: Int) = AppLocale.pick("$n months", "$n мес.", "$n oylik")
    fun years(n: Int) = AppLocale.pick("$n years", "$n лет", "$n yil")
    fun hours(n: Int) = AppLocale.pick("$n hours", "$n ч", "$n soat")
    fun rooms(n: Int) = AppLocale.pick("$n rooms", "$n комн.", "$n xona")
    fun roomsPlus(n: Int) = AppLocale.pick("$n+ rooms", "$n+ комн.", "$n+ xona")
    fun tenantsNow(n: Int) = AppLocale.pick("$n living here", "$n живёт", "$n kishi bor")
    fun tenantsNeeded(n: Int) = AppLocale.pick("$n needed", "нужно $n", "$n kishi kerak")
    fun upTo(amount: String) = AppLocale.pick("up to $amount", "до $amount", "$amount gacha")
    fun millions(v: Double) = AppLocale.pick("${v}M", "$v млн", "$v mln")
}

