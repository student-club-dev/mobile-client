/**
 * E'lon kataloglarining tarjima lug'ati.
 *
 * Kataloglar (`ServiceCatalog`, `ListingCatalog`, `JobCatalog`…) o'zbekcha yorliqlar bilan
 * yozilgan va o'sha holicha qoladi — ular kalitlar bilan yonma-yon turadi va serverdagi
 * spetsifikatsiyaning ko'zgusi. Tarjima esa **o'qish paytida** shu lug'atdan olinadi:
 * modeldagi `label` xossasi [trListing] ni chaqiradi.
 *
 * Shu sabab yangi yo'nalish qo'shilganda katalogga bitta qator, bu yerga bitta qator
 * yoziladi. Lug'atda topilmagan yorliq o'zbekcha holicha ko'rinadi — bo'sh joy emas.
 */
internal fun trListing(uz: String): String = when (AppLocale.current) {
    AppLanguage.UZ -> uz
    AppLanguage.EN -> EN[uz] ?: uz
    AppLanguage.RU -> RU[uz] ?: uz
}

/** Pul birligi — summadan keyin qo'yiladi ("150 000 UZS"). */
internal fun listingCurrency(): String = AppLocale.pick(en = "UZS", ru = "сум", uz = "so'm")

/** Sonli yorliqlar — lug'atga tushmaydi, chunki ichida qiymat bor. */
internal object ListingText {
    fun rooms(n: Int) = AppLocale.pick(en = "$n rooms", ru = "$n комн.", uz = "$n xonali")
    fun tenantsNow(n: Int) = AppLocale.pick(en = "$n living here", ru = "$n живёт", uz = "$n kishi bor")
    fun tenantsNeeded(n: Int) = AppLocale.pick(en = "$n needed", ru = "нужно $n", uz = "$n kishi kerak")
    fun roomsPlus(n: Int) = AppLocale.pick(en = "$n+ rooms", ru = "$n+ комн.", uz = "$n+ xona")
    fun upTo(amount: String) = AppLocale.pick(en = "up to $amount", ru = "до $amount", uz = "$amount gacha")
}

